// Writes src/sample-data.js from ../data/sample-clients.json, so the Worker never reads outside worker/.
// Run after the data file changes: npm run build:sample. tests/sample.test.mjs fails when the output is stale.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

export function sampleData() {
  const data = JSON.parse(readFileSync(join(root, '..', 'data', 'sample-clients.json'), 'utf8'))
  return {
    company: { name: data.company.name, yard: { label: data.company.yard.label, lat: data.company.yard.lat, lng: data.company.yard.lng } },
    trucks: data.trucks.map((t) => ({ ref: t.ref, name: t.name })),
    clients: data.clients.map((c) => ({
      ref: c.ref,
      name: c.name,
      address: c.address,
      lat: c.lat,
      lng: c.lng,
      type: c.type,
      priority: c.priority,
      opens_at: c.opens_at,
      notes: c.notes,
      billing: c.billing,
      price_cents: c.price_cents,
      truck: c.truck,
    })),
  }
}

export const render = (data) => `// GENERATED by tools/build-sample-data.mjs from data/sample-clients.json. Do not edit by hand.
// SAMPLE data: made-up names on real public streets, no house numbers. \`truck\` is the 1-based index into \`trucks\`.
export const SAMPLE = ${JSON.stringify(data, null, 2)}
`

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, 'src', 'sample-data.js'), render(sampleData()))
  console.log('wrote src/sample-data.js')
}
