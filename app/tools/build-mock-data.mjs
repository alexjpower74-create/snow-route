// Writes app/public/mock-data.js from data/sample-clients.json, for api.mock.js (development only, ?mock=1).
// The browser cannot read ../data, so the SAMPLE clients are copied into public/ once. Usage (from app/): node tools/build-mock-data.mjs
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const APP = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const src = JSON.parse(await readFile(path.join(APP, '..', 'data', 'sample-clients.json'), 'utf8'))

const company = { name: src.company.name, yard: { label: src.company.yard.label, lat: src.company.yard.lat, lng: src.company.yard.lng } }
const trucks = src.trucks.map((t, i) => ({ id: i + 1, name: t.name }))
const clients = src.clients.map((c, i) => ({
  id: i + 1, ref: c.ref, name: c.name, address: c.address, lat: c.lat, lng: c.lng, type: c.type, priority: c.priority,
  opens_at: c.opens_at, notes: c.notes || '', billing: c.billing, price_cents: c.price_cents, truck_id: c.truck,
}))

const out = `// Generated by app/tools/build-mock-data.mjs from data/sample-clients.json. Do not edit by hand.
// SAMPLE data for api.mock.js only (?mock=1). The real Worker seeds the same clients itself.
export const COMPANY = ${JSON.stringify(company)}
export const TRUCKS = ${JSON.stringify(trucks)}
export const CLIENTS = [
${clients.map((c) => '  ' + JSON.stringify(c)).join(',\n')},
]
`
await writeFile(path.join(APP, 'public', 'mock-data.js'), out)
console.log(`mock-data.js: ${clients.length} clients, ${trucks.length} trucks`)
